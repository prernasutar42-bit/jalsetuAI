// Helper to construct rich district payload
function buildDistrictPayload(d, timeUpdated) {
  const prob = d.baseProbability;
  const level = getRiskLevelFromProbability(prob);

  // Generate 24, 48, 72h forecast array
  const f24Prob = Math.min(1, Math.max(0, prob + (prob > 0.6 ? 0.04 : -0.02)));
  const f48Prob = Math.min(1, Math.max(0, prob + (prob > 0.6 ? -0.06 : -0.05)));
  const f72Prob = Math.min(1, Math.max(0, prob + (prob > 0.6 ? -0.15 : -0.08)));

  const forecast = [
    {
      hours: '24h',
      timeLabel: '+24 hours',
      probability: Number(f24Prob.toFixed(2)),
      level: getRiskLevelFromProbability(f24Prob),
      expectedRainfall_mm: Math.round(d.rainfall24h * 1.1),
    },
    {
      hours: '48h',
      timeLabel: '+48 hours',
      probability: Number(f48Prob.toFixed(2)),
      level: getRiskLevelFromProbability(f48Prob),
      expectedRainfall_mm: Math.round(d.rainfall24h * 0.85),
    },
    {
      hours: '72h',
      timeLabel: '+72 hours',
      probability: Number(f72Prob.toFixed(2)),
      level: getRiskLevelFromProbability(f72Prob),
      expectedRainfall_mm: Math.round(d.rainfall24h * 0.5),
    },
  ];

  // Factors in plain language
  const factors = [
    {
      feature: 'Precipitation volume',
      impact: d.rainfall24h > 120 ? 'high' : d.rainfall24h > 60 ? 'moderate' : 'low',
      text: `24 h rainfall is ${d.rainfall24h} mm, which is ${(d.rainfall24h / Math.max(1, d.normal24h)).toFixed(1)}x the seasonal normal (${d.normal24h} mm).`,
      weightPercent: 42,
    },
    {
      feature: 'River stage & discharge',
      impact: d.currentLevel_m >= d.warningLevel_m ? 'high' : 'moderate',
      text: d.topFactor,
      weightPercent: 33,
    },
    {
      feature: 'Watershed soil saturation',
      impact: d.catchmentSaturation > 80 ? 'high' : d.catchmentSaturation > 60 ? 'moderate' : 'low',
      text: `Catchment soil moisture is measured at ${d.catchmentSaturation}% capacity, limiting additional ground infiltration.`,
      weightPercent: 25,
    },
  ];

  const riverRatio = (d.currentLevel_m - d.warningLevel_m) / (d.dangerLevel_m - d.warningLevel_m);
  let riverStatus = 'normal';
  if (d.currentLevel_m >= d.dangerLevel_m) {
    riverStatus = 'danger';
  } else if (d.currentLevel_m >= d.warningLevel_m) {
    riverStatus = 'warning';
  }

  return {
    id: d.id,
    name: d.name,
    region: d.region,
    lat: d.lat,
    lon: d.lon,
    current_risk: {
      probability: prob,
      level,
      updated_at: timeUpdated,
    },
    forecast,
    factors,
    rainfall: {
      current_24h_mm: d.rainfall24h,
      normal_24h_mm: d.normal24h,
      trend: prob > 0.6 ? 'rising' : 'steady',
      anomaly_ratio: Number((d.rainfall24h / Math.max(1, d.normal24h)).toFixed(1)),
    },
    river: {
      name: d.riverName,
      current_m: d.currentLevel_m,
      warning_level_m: d.warningLevel_m,
      danger_level_m: d.dangerLevel_m,
      status: riverStatus,
      freeboard_m: Number((d.dangerLevel_m - d.currentLevel_m).toFixed(2)),
      dam_discharge_cusec: d.damDischarge_cusec,
    },
    soil_saturation_pct: d.catchmentSaturation,
  };
}

// Live store in memory that can be modified by admin refresh
let districtsStore = INITIAL_DISTRICTS.map((d) =>
  buildDistrictPayload(d, new Date(Date.now() - 4 * 60 * 1000).toISOString())
);

// Fetch all 36 districts
export async function getDistricts() {
  if (!USE_MOCK) {
    const zones = await apiFetch('/zones');
    return zones.map((z) => ({
      ...z,
      lat: z.centroid_lat,
      lon: z.centroid_lon,
      current_risk: z.current_risk || {
        probability: 0.20,
        level: 'low',
        updated_at: new Date().toISOString(),
      },
    }));
  }

  return mockFetch(() => [...districtsStore], 180);
}

// Fetch single district by id
export async function getDistrictById(id) {
  const numId = Number(id);
  if (!USE_MOCK) {
    return await apiFetch(`/zones/${numId}/risk`);
  }

  return mockFetch(() => {
    const found = districtsStore.find((d) => d.id === numId);
    if (!found) {
      throw new Error(`District with ID ${id} not found.`);
    }
    return { ...found };
  }, 120);
}

// Admin action: re-randomize predictions slightly
export async function refreshPredictions() {
  if (!USE_MOCK) {
    await apiFetch('/admin/run-prediction', { method: 'POST' });
    return await getDistricts();
  }

  return mockFetch(() => {
    const now = new Date().toISOString();
    districtsStore = districtsStore.map((d) => {
      const delta = (Math.random() - 0.48) * 0.1;
      const newProb = Math.min(0.98, Math.max(0.08, Number((d.current_risk.probability + delta).toFixed(2))));
      const newLevel = getRiskLevelFromProbability(newProb);
      const newRainfall = Math.round(d.rainfall.current_24h_mm * (1 + (Math.random() - 0.5) * 0.12));

      return {
        ...d,
        current_risk: {
          probability: newProb,
          level: newLevel,
          updated_at: now,
        },
        rainfall: {
          ...d.rainfall,
          current_24h_mm: newRainfall,
        },
      };
    });

    return [...districtsStore];
  }, 350);
}

// What-if scenario calculation calling backend model or fallback
export async function simulateWhatIf(zone_id, extra_rain_mm) {
  if (!USE_MOCK) {
    return await apiFetch('/risk/whatif', {
      method: 'POST',
      body: JSON.stringify({
        zone_id: Number(zone_id),
        extra_rain_mm: Number(extra_rain_mm),
      }),
    });
  }

  return mockFetch(() => {
    const district = districtsStore.find((d) => d.id === Number(zone_id));
    const baseProb = district ? district.current_risk.probability : 0.5;
    const boost = (extra_rain_mm / 100.0) * (1 - baseProb * 0.45) * 0.7;
    const simProb = Math.min(0.99, Number((baseProb + boost).toFixed(2)));
    return {
      zone_id: Number(zone_id),
      zone_name: district?.name || 'District',
      base_probability: baseProb,
      simulated_probability: simProb,
      level: getRiskLevelFromProbability(simProb),
      added_rainfall_mm: extra_rain_mm,
      factors: district?.factors || [],
    };
  }, 100);
}
